begin;
create extension if not exists pgtap with schema extensions;
select plan(36);
select has_table('public','profiles','Profiles table exists');
select has_table('public','tasks','Tasks table exists');
select has_table('public','recording_files','Recording records exist');
select has_table('public','wallet_accounts','Wallet accounts exist');
select has_table('public','wallet_ledger_entries','Ledger exists');
select has_table('public','wallet_journal_postings','Journal postings exist');
select has_table('public','identity_verifications','KYC exists');
select has_table('public','withdrawal_requests','Withdrawals exist');
select has_function('public','allocate_my_tasks',array[]::text[],'Allocation function exists');
select has_function('public','submit_my_task',array['uuid','uuid'],'Submission function exists');
select has_function('public','request_my_withdrawal',array['bigint','uuid','uuid'],'Withdraw function exists');
select has_function('public','is_admin',array[]::text[],'Admin authorization function exists');
select ok((select relrowsecurity from pg_class where oid='public.profiles'::regclass),'Profiles have RLS');
select ok((select relrowsecurity from pg_class where oid='public.wallet_ledger_entries'::regclass),'Ledger has RLS');
select ok((select relrowsecurity from pg_class where oid='public.identity_documents'::regclass),'KYC documents have RLS');
select ok((select not public from storage.buckets where id='voice-recordings'),'Voice recordings bucket is private');
select ok((select not public from storage.buckets where id='identity-documents'),'Identity documents bucket is private');
select has_table('public','club_settings','Club editorial settings exist');
select has_table('public','club_courses','Member Club courses exist');
select has_table('public','club_modules','Member Club course modules exist');
select has_table('public','club_lessons','Member Club lessons exist');
select has_table('public','club_lesson_progress','Member Club progress exists');
select has_table('public','manual_payout_confirmations','Manual payment proof table exists');
select ok((select not public from storage.buckets where id='club-materials'),'Lesson PDFs are in a private storage bucket');
select has_function('public','auto_accept_due_submissions',array['integer'],'Timed task acceptance exists');
select has_function('public','community_leaderboard',array['text'],'Community ranking exists');
select has_function('public','staff_set_leaderboard_points',array['uuid','text','integer','uuid','text'],'Admin ranking edit exists');
select has_function('public','staff_confirm_manual_payout',array['uuid','uuid','text','text'],'Manual payment confirmation exists');
select has_function('public','decide_identity_secure',array['uuid','uuid','boolean','text'],'Manual KYC decision exists');
select ok((select relrowsecurity from pg_class where oid='public.club_courses'::regclass),'Courses enforce RLS');
select ok((select relrowsecurity from pg_class where oid='public.club_lessons'::regclass),'Lessons enforce RLS');
select ok((select relrowsecurity from pg_class where oid='public.club_lesson_progress'::regclass),'Lesson progress enforces RLS');
select ok(not has_function_privilege('authenticated','public.staff_confirm_manual_payout(uuid,uuid,text,text)','execute'),'Members cannot settle payouts');
select ok(not has_function_privilege('authenticated','public.staff_set_leaderboard_points(uuid,text,integer,uuid,text)','execute'),'Members cannot adjust rankings');
select ok(not has_function_privilege('authenticated','public.auto_accept_due_submissions(integer)','execute'),'Members cannot force task approval');
select ok((select count(*)=1 from cron.job where jobname='voicetask-auto-accept-due' and active),'Timed task acceptance worker scheduled');
select * from finish();
rollback;
